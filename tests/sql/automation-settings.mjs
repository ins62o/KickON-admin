import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import process from 'node:process';
import console from 'node:console';
import {URL} from 'node:url';
const {PGlite}=await import(process.env.PGLITE_MODULE_PATH||'@electric-sql/pglite');
const db=new PGlite();
await db.exec(`
 create role anon;create role authenticated;create role service_role;
 create schema auth;create schema cron;
 create type public.admin_role as enum ('viewer','operator','super_admin');
 create function auth.role() returns text language sql as $$select current_setting('request.jwt.claim.role',true)$$;
 create function public.is_admin(public.admin_role) returns boolean language sql as $$select coalesce(current_setting('qa.admin',true)='yes',false)$$;
 create table cron.job(jobid bigint primary key,jobname text,active boolean);
 create function cron.unschedule(bigint) returns boolean language plpgsql as $$begin delete from cron.job where jobid=$1;return found;end$$;
 insert into cron.job values(3,'kickon-fixture-cheer-retention',false),(2,'kickon-football-provider-usage-retention',true);
 create table public.fixture_cheer_messages(id int primary key);insert into public.fixture_cheer_messages values(1),(2);
 create table public.push_runtime_config(singleton boolean,mode text,max_attempts int,base_retry_delay_seconds int,max_retry_delay_seconds int);
 insert into public.push_runtime_config values(true,'SHADOW',5,5,300);
 create table public.push_domain_policies(domain text,mode text);insert into public.push_domain_policies values('MATCH','FULL'),('COMMUNITY','FULL');
 create function public.push_notification_domain(text) returns text language sql as $$select case when $1 in ('MATCH','LINEUP') then 'MATCH' when $1 in ('COMMUNITY','ATTENDANCE') then 'COMMUNITY' end$$;
 create function public.effective_push_mode(text) returns text language sql as $$select case when (select mode from public.push_runtime_config)='OFF' then 'OFF' else coalesce((select mode from public.push_domain_policies where domain=$1),'SHADOW') end$$;
`);
const sql=await fs.readFile(new URL('../../supabase/migrations/202610200008_admin_automation_settings.sql',import.meta.url),'utf8');
await db.exec(sql);
assert.deepEqual((await db.query('select jobid from cron.job')).rows,[{jobid:2}]);
assert.equal((await db.query('select count(*)::int as n from public.fixture_cheer_messages')).rows[0].n,2);
await db.exec(sql); // Reapplying does not touch other schedules or messages.
await db.exec('set role anon');await assert.rejects(db.query('select public.get_admin_push_settings()'),/permission denied/);await db.exec('reset role');
await db.exec('set role authenticated');await assert.rejects(db.query('select public.get_admin_push_settings()'),/ADMIN_REQUIRED/);await db.exec('reset role');
await db.exec("set qa.admin='yes';set role authenticated");
const settings=(await db.query('select public.get_admin_push_settings() as settings')).rows[0].settings;
assert.equal(settings.global_disabled,false);assert.equal(settings.max_attempts,5);assert.equal(settings.notifications.length,5);
assert.equal(settings.notifications.find(row=>row.type==='MATCH').mode,'FULL');
assert.deepEqual(settings.notifications.find(row=>row.type==='SYSTEM'),{type:'SYSTEM',domain:null,mode:'SHADOW'});
await assert.rejects(db.query('select * from public.push_runtime_config'),/permission denied/);
await db.exec("reset role;set qa.admin='no';set request.jwt.claim.role='service_role';set role service_role");
assert.equal((await db.query('select public.get_admin_push_settings() as settings')).rows[0].settings.max_attempts,5);
await db.exec("reset role;update public.push_runtime_config set mode='OFF'");
assert.ok((await db.query('select public.get_admin_push_settings() as settings')).rows[0].settings.notifications.every(row=>row.mode==='OFF'));
await db.exec('delete from public.push_runtime_config');await assert.rejects(db.query('select public.get_admin_push_settings()'),/PUSH_RUNTIME_CONFIG_MISSING/);
await db.exec("insert into cron.job values(3,'kickon-fixture-cheer-retention',true)");
await assert.rejects(db.exec(sql),/CHEER_RETENTION_MUST_BE_DISABLED/);await db.exec('rollback');
assert.equal((await db.query('select count(*)::int as n from cron.job')).rows[0].n,2);
await db.close();console.log('PASS automation SQL: disabled schedule only, no message deletion, admin-only settings, effective modes and missing config');
