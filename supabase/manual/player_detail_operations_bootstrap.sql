drop policy if exists "data center users create own data reports"
  on public.user_data_reports;
create policy "data center users create own data reports"
  on public.user_data_reports for insert to authenticated
  with check (reporter_id = (select auth.uid()));

drop policy if exists "data center operators read data reports"
  on public.user_data_reports;
create policy "data center operators read data reports"
  on public.user_data_reports for select to authenticated
  using (
    reporter_id = (select auth.uid())
    or public.admin_has_capability('support.read')
    or public.admin_has_capability('data.read')
  );

drop policy if exists "data center operators update data reports"
  on public.user_data_reports;
create policy "data center operators update data reports"
  on public.user_data_reports for update to authenticated
  using (
    public.admin_has_capability('support.write')
    or public.admin_has_capability('data.write')
  )
  with check (
    public.admin_has_capability('support.write')
    or public.admin_has_capability('data.write')
  );

drop policy if exists "data center operators read report history"
  on public.user_data_report_history;
create policy "data center operators read report history"
  on public.user_data_report_history for select to authenticated
  using (
    public.admin_has_capability('support.read')
    or public.admin_has_capability('data.read')
  );

drop policy if exists "data center operators read sync runs"
  on public.sync_runs;
create policy "data center operators read sync runs"
  on public.sync_runs for select to authenticated
  using (
    public.admin_has_capability('sync.read')
    or public.admin_has_capability('system.read')
  );

drop policy if exists "data center operators create sync runs"
  on public.sync_runs;
create policy "data center operators create sync runs"
  on public.sync_runs for insert to authenticated
  with check (
    public.admin_has_capability('sync.run')
    and requested_by = (select auth.uid())
  );

drop policy if exists "data center operators update sync runs"
  on public.sync_runs;
create policy "data center operators update sync runs"
  on public.sync_runs for update to authenticated
  using (public.admin_has_capability('sync.run'))
  with check (public.admin_has_capability('sync.run'));

drop policy if exists "data center operators read overrides"
  on public.manual_overrides;
create policy "data center operators read overrides"
  on public.manual_overrides for select to authenticated
  using (public.admin_has_capability('data.read'));

drop policy if exists "data center operators read audit logs"
  on public.admin_audit_logs;
create policy "data center operators read audit logs"
  on public.admin_audit_logs for select to authenticated
  using (public.admin_has_capability('audit.read'));

revoke all on table public.user_data_reports,
