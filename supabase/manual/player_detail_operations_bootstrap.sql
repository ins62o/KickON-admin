begin;

-- Partially initialized production projects may already have admin_users and
-- admin_has_capability, while the legacy operations tables are still absent.
-- This bootstrap creates only the prerequisites required by
-- 202608300002_player_operations.sql and 202608300003_provider_snapshots.sql.

do $$
begin
  if to_regtype('public.report_status') is null then
    create type public.report_status as enum (
      'open', 'in_review', 'resolved', 'rejected', 'on_hold'
    );
  end if;
  if to_regtype('public.report_priority') is null then
    create type public.report_priority as enum (
      'low', 'normal', 'high', 'urgent'
    );
  end if;
  if to_regtype('public.sync_run_status') is null then
    create type public.sync_run_status as enum (
      'queued', 'running', 'succeeded', 'partial', 'failed', 'cancelled'
    );
  end if;
end
$$;

-- Compatibility contract used by the older player/provider migrations.
-- The current authorization source remains admin_users.
create or replace function public.is_admin(required_role text default 'viewer')
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_users administrator
    where administrator.user_id = (select auth.uid())
      and administrator.is_active
      and case administrator.role::text
        when 'viewer' then 10
        when 'support' then 10
        when 'operator' then 20
        when 'moderator' then 20
        when 'data_editor' then 30
        when 'admin' then 30
        when 'super_admin' then 40
        else 0
      end >= case lower(coalesce(required_role, 'viewer'))
        when 'viewer' then 10
        when 'operator' then 20
        when 'admin' then 30
        when 'super_admin' then 40
        else 100
      end
  );
$$;

revoke all on function public.is_admin(text) from public, anon;
grant execute on function public.is_admin(text) to authenticated, service_role;

create table if not exists public.user_data_reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references auth.users(id) on delete cascade,
  entity_type text not null check (
    entity_type in ('team', 'player', 'fixture', 'standing', 'ranking', 'other')
  ),
  entity_id text,
  field_path text,
  current_value jsonb,
  proposed_value jsonb,
  description text not null check (char_length(description) between 3 and 4000),
  evidence_urls text[] not null default '{}',
  status public.report_status not null default 'open',
  priority public.report_priority not null default 'normal',
  assignee_id uuid references public.admin_users(user_id) on delete set null,
  resolution_note text,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

